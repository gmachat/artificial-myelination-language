"""AML-to-JavaScript compiler targeting modern Node.js."""

from __future__ import annotations

import json
import re

from .compiler import CompileError, NAME, PROFILES
from .expression import ExpressionError, render_expression
from .typesystem import parse_type, split_top_level, validate_type


JS_TYPES = {
    "Any": "Any",
    "Bool": "Bool",
    "Float": "Float",
    "Int": "Int",
    "Text": "Text",
}

RUNTIME = """\
class AMLFailure extends Error {}

function __amlActual(value) {
  if (value === null) return "none";
  if (Array.isArray(value)) return "list";
  return typeof value;
}

function __amlExpect(place, value, expected) {
  const valid = __amlValid(value, expected);
  if (!valid) {
    throw new AMLFailure(`type | ${place} expected ${expected}, got ${__amlActual(value)}`);
  }
}

function __amlValid(value, expected) {
  if (expected === "Any") return true;
  if (expected.startsWith("Optional[")) {
    return value === null || __amlValid(value, expected.slice(9, -1));
  }
  if (expected.startsWith("List[")) {
    return Array.isArray(value) && value.every(item => __amlValid(item, expected.slice(5, -1)));
  }
  if (Object.hasOwn(__amlRecords, expected)) {
    const fields = __amlRecords[expected];
    return value !== null && !Array.isArray(value) && typeof value === "object" &&
      Object.keys(value).length === Object.keys(fields).length &&
      Object.entries(fields).every(([name, type]) => Object.hasOwn(value, name) && __amlValid(value[name], type));
  }
  return (expected === "Bool" && typeof value === "boolean") ||
    (expected === "Float" && typeof value === "number" && Number.isFinite(value)) ||
    (expected === "Int" && Number.isInteger(value)) ||
    (expected === "Text" && typeof value === "string");
}

function __amlRequire(condition, task, kind, expression) {
  if (!condition) {
    throw new AMLFailure(`contract | ${task} ${kind} failed: ${expression}`);
  }
}
"""


def _expression(source: str) -> str:
    """Parse and render one target-neutral AML expression."""
    try:
        return render_expression(source, "javascript")
    except ExpressionError as error:
        raise CompileError(error.message, 1, error.column) from error


def _task(text: str, line: int, records: set[str]) -> tuple[str, list[tuple[str, str]], str | None]:
    match = re.fullmatch(
        rf"task\s+({NAME})(?:\((.*?)\))?(?:\s*->\s*(.+?))?:", text
    )
    if not match:
        raise CompileError("invalid task declaration", line)
    name, raw_parameters, return_type = match.groups()
    parameters: list[tuple[str, str]] = []
    if raw_parameters:
        for parameter in split_top_level(raw_parameters):
            item = re.fullmatch(rf"\s*({NAME})\s*:\s*(.+?)\s*", parameter)
            if not item:
                raise CompileError("parameters must use 'name: Type'", line)
            parameter_name, parameter_type = item.groups()
            try:
                parsed = parse_type(parameter_type)
                validate_type(parsed, records)
            except ValueError as error:
                raise CompileError(str(error), line) from error
            parameters.append((parameter_name, parsed.canonical()))
    if return_type:
        try:
            parsed_return = parse_type(return_type)
            validate_type(parsed_return, records)
            return_type = parsed_return.canonical()
        except ValueError as error:
            raise CompileError(str(error), line) from error
    return name, parameters, return_type


def compile_javascript(source: str, filename: str = "<memory>") -> str:
    """Compile AML source into dependency-free JavaScript for Node.js."""
    del filename
    output = [
        "// Generated by AML 0.8.0.dev0. Do not edit generated code.",
        '"use strict";',
        "",
    ]
    app_seen = False
    profile_name: str | None = None
    task_seen = False
    main_seen = False
    open_blocks: list[str] = []
    current_task: str | None = None
    current_return_type: str | None = None
    current_ensures: list[str] = []
    current_has_return = False
    contracts: dict[str, dict[str, list[str]]] = {}
    records: dict[str, dict[str, str]] = {}
    current_record: str | None = None

    def close_to(indent: int) -> str | None:
        closed: str | None = None
        while len(open_blocks) > indent:
            closed = open_blocks.pop()
            output.append("  " * len(open_blocks) + "}")
        return closed

    def finish_task(line: int) -> None:
        nonlocal current_task, current_return_type, current_ensures, current_has_return
        if current_task and current_ensures and not current_has_return:
            raise CompileError(
                f"task '{current_task}' has ensure contracts but no return", line
            )
        if current_task and current_return_type and not current_has_return:
            raise CompileError(
                f"task '{current_task}' declares a return type but has no return", line
            )
        current_task = None
        current_return_type = None
        current_ensures = []
        current_has_return = False

    lines = source.splitlines()
    for line_number, raw in enumerate(lines, start=1):
        if "\t" in raw:
            raise CompileError("tabs are not allowed; use two spaces", line_number)
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        leading = len(raw) - len(raw.lstrip(" "))
        if leading % 2:
            raise CompileError("indentation must use multiples of two spaces", line_number)
        indent = leading // 2
        text = raw.strip()

        if not app_seen:
            app = re.fullmatch(rf"app\s+({NAME})", text)
            if not app or indent:
                raise CompileError("the first declaration must be 'app <name>'", line_number)
            app_seen = True
            output.extend([f"const __amlApp = {json.dumps(app.group(1))};", ""])
            continue

        if indent == 0 and text.startswith("record "):
            if task_seen:
                raise CompileError("records must appear before the first task", line_number)
            match = re.fullmatch(rf"record\s+({NAME}):", text)
            if not match:
                raise CompileError("use 'record <Name>:'", line_number)
            current_record = match.group(1)
            if current_record in records:
                raise CompileError(f"duplicate record '{current_record}'", line_number)
            records[current_record] = {}
            continue
        if current_record and indent == 1:
            field = re.fullmatch(rf"({NAME})\s*:\s*(.+)", text)
            if not field:
                raise CompileError("record fields must use 'name: Type'", line_number)
            field_name, field_type = field.groups()
            if field_name in records[current_record]:
                raise CompileError(f"duplicate field '{field_name}'", line_number)
            try:
                records[current_record][field_name] = parse_type(field_type).canonical()
            except ValueError as error:
                raise CompileError(str(error), line_number) from error
            continue
        if indent == 0:
            current_record = None

        if indent == 0 and text.startswith("profile "):
            if task_seen:
                raise CompileError("profile must appear before the first task", line_number)
            if profile_name:
                raise CompileError("only one profile is allowed", line_number)
            profile = re.fullmatch(rf"profile\s+({NAME})", text)
            if not profile or profile.group(1) not in PROFILES:
                choices = ", ".join(PROFILES)
                raise CompileError(f"unknown profile; expected one of: {choices}", line_number)
            profile_name = profile.group(1)
            capabilities = json.dumps(list(PROFILES[profile_name]))
            output.extend(
                [
                    f"const __amlProfile = {json.dumps(profile_name)};",
                    f"const __amlCapabilities = {capabilities};",
                    "",
                    RUNTIME.rstrip(),
                    "",
                ]
            )
            continue

        if indent == 0 and text.startswith("task "):
            if not profile_name:
                raise CompileError("declare a profile before the first task", line_number)
            close_to(0)
            finish_task(line_number)
            for record_name, fields in records.items():
                if not fields:
                    raise CompileError(f"record '{record_name}' needs at least one field", line_number)
                for field_type in fields.values():
                    try:
                        parsed = parse_type(field_type)
                        validate_type(parsed, set(records))
                    except ValueError as error:
                        raise CompileError(str(error), line_number) from error
            task_name, parameters, return_type = _task(text, line_number, set(records))
            if task_name == "main":
                if main_seen:
                    raise CompileError("only one main task is allowed", line_number)
                if parameters or return_type:
                    raise CompileError("main cannot have parameters or a return type", line_number)
                main_seen = True
            task_seen = True
            current_task = task_name
            current_return_type = return_type
            contracts[task_name] = {"require": [], "ensure": []}
            names = ", ".join(name for name, _ in parameters)
            output.append(f"function {task_name}({names}) {{")
            open_blocks.append("task")
            for parameter_name, parameter_type in parameters:
                output.append(
                    "  "
                    + f"__amlExpect({json.dumps(f'{task_name}.{parameter_name}')}, "
                    + f"{parameter_name}, {json.dumps(parameter_type)});"
                )
            continue

        if not task_seen:
            raise CompileError("statements must be inside a task", line_number)
        closed = close_to(indent)
        if indent != len(open_blocks):
            raise CompileError("unexpected indentation", line_number)
        js_indent = "  " * indent

        if text == "else:":
            if closed != "if":
                raise CompileError("else must follow an if block", line_number)
            output.append(js_indent + "else {")
            open_blocks.append("else")
            continue
        if text.startswith("require "):
            condition = text[8:].strip()
            if not condition:
                raise CompileError("require needs a condition", line_number)
            contracts[current_task]["require"].append(condition)  # type: ignore[index]
            output.append(
                js_indent
                + f"__amlRequire(Boolean({_expression(condition)}), "
                + f"{json.dumps(current_task)}, \"require\", {json.dumps(condition)});"
            )
            continue
        if text.startswith("ensure "):
            if indent != 1:
                raise CompileError("ensure must be at the top level of a task", line_number)
            condition = text[7:].strip()
            if not condition:
                raise CompileError("ensure needs a condition", line_number)
            if "result" not in condition:
                raise CompileError("ensure must describe 'result'", line_number)
            current_ensures.append(condition)
            contracts[current_task]["ensure"].append(condition)  # type: ignore[index]
            continue
        if text.startswith("let "):
            match = re.fullmatch(rf"let\s+({NAME})\s*=\s*(.+)", text)
            if not match:
                raise CompileError("use 'let <name> = <expression>'", line_number)
            name, value = match.groups()
            output.append(js_indent + f"const {name} = {_expression(value)};")
            continue
        if text.startswith("show "):
            output.append(js_indent + f"console.log({_expression(text[5:].strip())});")
            continue
        if text == "return":
            if current_ensures:
                raise CompileError("a task with ensure contracts must return a value", line_number)
            output.append(js_indent + "return;")
            continue
        if text.startswith("return "):
            value = _expression(text[7:].strip())
            current_has_return = True
            if current_ensures or current_return_type:
                output.append(js_indent + f"const result = {value};")
                for condition in current_ensures:
                    output.append(
                        js_indent
                        + f"__amlRequire(Boolean({_expression(condition)}), "
                        + f"{json.dumps(current_task)}, \"ensure\", {json.dumps(condition)});"
                    )
                if current_return_type:
                    output.append(
                        js_indent
                        + f"__amlExpect({json.dumps(f'{current_task}.result')}, result, "
                        + f"{json.dumps(current_return_type)});"
                    )
                output.append(js_indent + "return result;")
            else:
                output.append(js_indent + f"return {value};")
            continue
        if text.startswith("fail "):
            output.append(js_indent + f"throw new AMLFailure(String({_expression(text[5:].strip())}));")
            continue
        if text.startswith("if ") and text.endswith(":"):
            condition = text[3:-1].strip()
            if not condition:
                raise CompileError("if requires a condition", line_number)
            output.append(js_indent + f"if ({_expression(condition)}) {{")
            open_blocks.append("if")
            continue
        output.append(js_indent + _expression(text) + ";")

    if not app_seen:
        raise CompileError("empty source; expected 'app <name>'", 1)
    close_to(0)
    finish_task(max(1, len(lines)))
    if not profile_name:
        raise CompileError("application must declare a profile", max(1, len(lines)))
    if not task_seen:
        raise CompileError("application must define at least one task", max(1, len(lines)))
    output.extend(
        [
            "",
            f"const __amlRecords = {json.dumps(records, sort_keys=True)};",
            f"const __amlContracts = {json.dumps(contracts, sort_keys=True)};",
        ]
    )
    if main_seen:
        output.extend(
            [
                "",
                "try {",
                "  main();",
                "} catch (error) {",
                "  if (error instanceof AMLFailure) {",
                '    console.error(`AML_ERROR: ${error.message}`);',
                "    process.exitCode = 1;",
                "  } else {",
                "    throw error;",
                "  }",
                "}",
            ]
        )
    output.append("")
    return "\n".join(output)

