use std::collections::BTreeMap;

use crate::{react, CompileError};

pub const REACT_VERSION: &str = "19.3.1";
pub const VITE_VERSION: &str = "8.3.8";
pub const VITE_REACT_VERSION: &str = "6.3.0";

fn title(value: &str) -> String {
    value
        .split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or(String::new(), |first| {
                first.to_uppercase().chain(chars).collect()
            })
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn sample(name: &str, kind: &str) -> String {
    match kind {
        "Text" => format!("\"AML {}\"", name.replace('_', " ")),
        "Int" => "0".into(),
        "Float" => "0.0".into(),
        "Bool" => "false".into(),
        _ => "null".into(),
    }
}

pub fn project_files(source: &str) -> Result<BTreeMap<String, String>, CompileError> {
    let info = react::component_info(source)?;
    let component = react::compile(source)?;
    let package_name = info.app_name.to_lowercase().replace('_', "-");
    let page_title = title(&info.app_name);
    let element = if info.props.is_empty() {
        "<App />".to_string()
    } else {
        format!(
            "<App {} />",
            info.props
                .iter()
                .map(|(name, kind)| format!("{name}={{{}}}", sample(name, kind)))
                .collect::<Vec<_>>()
                .join(" ")
        )
    };
    let package = format!(
        r#"{{
  "name": "{package_name}",
  "private": true,
  "version": "0.0.0",
  "type": "module",
  "scripts": {{
    "dev": "vite",
    "build": "vite build",
    "preview": "vite preview"
  }},
  "dependencies": {{
    "react": "^{REACT_VERSION}",
    "react-dom": "^{REACT_VERSION}"
  }},
  "devDependencies": {{
    "@vitejs/plugin-react": "^{VITE_REACT_VERSION}",
    "vite": "^{VITE_VERSION}"
  }}
}}
"#
    );
    let main = format!(
        r#"import {{ StrictMode }} from "react";
import {{ createRoot }} from "react-dom/client";
import App from "./App.jsx";
import ErrorBoundary from "./ErrorBoundary.jsx";
import "./styles.css";

const root = document.getElementById("root");

if (!root) {{
  throw new Error("AML web root element was not found");
}}

createRoot(root).render(
  <StrictMode>
    <ErrorBoundary>
      {element}
    </ErrorBoundary>
  </StrictMode>,
);
"#
    );
    let boundary = r#"import { Component } from "react";

export default class ErrorBoundary extends Component {
  constructor(props) { super(props); this.state = { error: null }; }
  static getDerivedStateFromError(error) { return { error }; }
  componentDidCatch(error, details) { console.error("AML web application error", error, details); }
  render() {
    if (this.state.error) return <main className="aml-error" role="alert"><h1>Something went wrong</h1><p>{this.state.error.message}</p></main>;
    return this.props.children;
  }
}
"#;
    let styles = r#":root { font-family: Inter, ui-sans-serif, system-ui, sans-serif; color: #172033; background: #f4f7fb; }
* { box-sizing: border-box; }
body { margin: 0; min-width: 320px; min-height: 100vh; }
button, input { font: inherit; }
button { border: 0; border-radius: .65rem; padding: .7rem 1rem; color: white; background: #3157d5; cursor: pointer; }
button:hover { background: #2546b7; }
button:focus-visible, input:focus-visible { outline: 3px solid #8ba4ff; outline-offset: 2px; }
input { width: 100%; border: 1px solid #bdc7da; border-radius: .65rem; padding: .7rem .8rem; background: white; }
#root { width: min(100% - 2rem, 48rem); margin: 0 auto; padding: 4rem 0; }
#root > * { padding: 2rem; border: 1px solid #dce3ef; border-radius: 1rem; background: white; box-shadow: 0 1rem 3rem rgb(28 43 75 / 10%); }
.aml-error { color: #8a1c1c; }
"#;
    let html = format!(
        r#"<!doctype html>
<html lang="en"><head><meta charset="UTF-8" /><meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta name="description" content="{page_title}, generated by AML" /><title>{page_title}</title></head>
<body><div id="root"></div><script type="module" src="/src/main.jsx"></script></body></html>
"#
    );
    let readme = format!("# {page_title}\n\nGenerated from AML component `{}`.\n\n```sh\nnpm install\nnpm run dev\n```\n", info.component_name);
    Ok(BTreeMap::from([
        (".gitignore".into(), "node_modules/\ndist/\n.env\n.env.*\n".into()),
        ("README.md".into(), readme), ("index.html".into(), html), ("package.json".into(), package),
        ("vite.config.js".into(), "import { defineConfig } from \"vite\";\nimport react from \"@vitejs/plugin-react\";\nexport default defineConfig({ plugins: [react()] });\n".into()),
        ("src/App.jsx".into(), component), ("src/ErrorBoundary.jsx".into(), boundary.into()),
        ("src/main.jsx".into(), main), ("src/styles.css".into(), styles.into()),
    ]))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn generates_complete_project() {
        let source = "app demo\nprofile web\ncomponent Demo:\n  view:\n    heading \"Hello\"\n";
        let files = project_files(source).unwrap();
        assert_eq!(files.len(), 9);
        assert!(files["package.json"].contains("vite build"));
        assert!(files["src/App.jsx"].contains("export function Demo"));
    }
}
